// KB計算ルール Excel ダウンロード
import * as XLSX from 'xlsx'

export function downloadKbRulesXlsx() {
  const wb = XLSX.utils.book_new()

  // ===== Sheet 1: 計算ルール概要 =====
  const s1 = [
    ['VAVITTE KB計算ルール 最終確定版'],
    ['作成日: 2026年4月13日'],
    [],
    ['■ 基本計算式'],
    ['KB = 定価 × (サロン価格率 − 代理店原価率) × 数量'],
    [],
    ['■ 定価の逆算方法'],
    ['定価 = BカートAPI最高単価 ÷ 0.65'],
    ['※ 同月・同商品名の最高単価 = サロン1〜5個価格(定価の65%)'],
    [],
    ['■ 判定の優先順位(コード上)'],
    ['1. 代理店にKB掛け率が設定されているか? → 未設定なら従来方式(5/13, 1/3)'],
    ['2. ミカエル or 6+1 を含むか? → ミカエル計算(セット価格÷6÷0.60)'],
    ['3. エンジェル or 業務用 を含むか? → 常に65%(数量無関係)'],
    ['4. 上記以外(店販用単品) → 1〜5個:65%  6個以上:60%'],
    [],
    ['■ その他の控除項目'],
    ['項目', '計算方法'],
    ['システム利用料', 'KB対象注文件数 × 300円'],
    ['決済手数料', '対象決済(クレジット/Paid/代金引換)の売上 × 3%'],
    ['消費税', '(KB合計 − システム利用料 − 決済手数料) × 10%'],
    [],
    ['■ ソースコード'],
    ['計算関数', 'src/pages/KickbackManage.jsx → calcKbFromProduct()'],
    ['PDF生成', 'src/lib/generateKickbackPdf.js'],
    ['代理店設定', 'src/pages/Dealers.jsx'],
  ]
  const ws1 = XLSX.utils.aoa_to_sheet(s1)
  ws1['!cols'] = [{ wch: 30 }, { wch: 55 }]
  XLSX.utils.book_append_sheet(wb, ws1, '計算ルール概要')

  // ===== Sheet 2: サロン価格率 =====
  const s2 = [
    ['サロン価格率(商品タイプ別)'],
    [],
    ['商品タイプ', '判定条件', 'サロン価格率', '備考'],
    ['店販用単品 1〜5個', '「店販用」含む＆数量1〜5', '65%', '通常価格'],
    ['店販用単品 6個以上', '「店販用」含む＆数量6以上', '60%', 'ボリュームディスカウント'],
    ['業務用単品', '「業務用」を含む', '65%(何個でも一律)', '数量に関係なく一律'],
    ['エンジェル', 'セット名に「エンジェル」含む', '65%(何個でも一律)', '業務用と同じ扱い'],
    ['ミカエル/6+1セット', '「ミカエル」or「6+1」含む', '60%(常に6個計算)', 'セット価格÷6で単品逆算'],
    [],
    ['代理店原価率(一律・代理店ごと設定)'],
    [],
    ['代理店タイプ', '原価率', '備考', '設定場所'],
    ['タイプA', '定価 × 45%', '数量に関係なく一律', '代理店管理→詳細→KB掛け率'],
    ['タイプB', '定価 × 40%', '数量に関係なく一律', '同上'],
  ]
  const ws2 = XLSX.utils.aoa_to_sheet(s2)
  ws2['!cols'] = [{ wch: 25 }, { wch: 35 }, { wch: 25 }, { wch: 35 }]
  XLSX.utils.book_append_sheet(wb, ws2, 'サロン価格率')

  // ===== Sheet 3: KB早見表 =====
  const s3 = [
    ['KB早見表(定価¥10,000の商品)'],
    [],
    ['■ 代理店原価率 45%'],
    ['商品タイプ', '1個あたりKB', 'セットKB', '計算式'],
    ['店販単品 1〜5個', 10000 * (0.65 - 0.45), '', '¥10,000 × (65%−45%) = ¥2,000'],
    ['店販単品 6個以上', 10000 * (0.60 - 0.45), '', '¥10,000 × (60%−45%) = ¥1,500'],
    ['業務用/エンジェル', 10000 * (0.65 - 0.45), '', '¥10,000 × (65%−45%) = ¥2,000'],
    ['ミカエル 1セット', '', 10000 * (0.60 - 0.45) * 6, '¥10,000 × (60%−45%) × 6 = ¥9,000'],
    [],
    ['■ 代理店原価率 40%'],
    ['商品タイプ', '1個あたりKB', 'セットKB', '計算式'],
    ['店販単品 1〜5個', 10000 * (0.65 - 0.40), '', '¥10,000 × (65%−40%) = ¥2,500'],
    ['店販単品 6個以上', 10000 * (0.60 - 0.40), '', '¥10,000 × (60%−40%) = ¥2,000'],
    ['業務用/エンジェル', 10000 * (0.65 - 0.40), '', '¥10,000 × (65%−40%) = ¥2,500'],
    ['ミカエル 1セット', '', 10000 * (0.60 - 0.40) * 6, '¥10,000 × (60%−40%) × 6 = ¥12,000'],
  ]
  const ws3 = XLSX.utils.aoa_to_sheet(s3)
  ws3['!cols'] = [{ wch: 25 }, { wch: 18 }, { wch: 18 }, { wch: 40 }]
  // 金額フォーマット
  const yenFmt = '¥#,##0'
  for (const r of [5, 6, 7, 8, 12, 13, 14, 15]) {
    const bRef = `B${r}`
    const cRef = `C${r}`
    if (ws3[bRef] && ws3[bRef].v) ws3[bRef].z = yenFmt
    if (ws3[cRef] && ws3[cRef].v) ws3[cRef].z = yenFmt
  }
  XLSX.utils.book_append_sheet(wb, ws3, 'KB早見表')

  // ===== Sheet 4: 計算例 =====
  const retail = 10000
  const s4 = [
    ['KB計算例(代理店原価率 45%)'],
    [],
    ['商品名', 'Bカート単価', '数量', '最高単価', '定価(逆算)', 'サロン価格率', 'KB金額', '計算過程'],
    ['ビタミンクリーム50g(店販用単品)', 6500, 3, 6500, retail, '65%', retail * 0.20 * 3, '定価¥10,000 × 20% × 3個 = ¥6,000'],
    ['ビタミンクリーム50g(店販用単品)', 6000, 6, 6500, retail, '60%', retail * 0.15 * 6, '定価¥10,000 × 15% × 6個 = ¥9,000'],
    ['ビタミンクリーム50g(業務用単品)', 6500, 8, 6500, retail, '65%(業務用一律)', retail * 0.20 * 8, '定価¥10,000 × 20% × 8個 = ¥16,000(業務用は常に65%)'],
    ['6+1ビタミンクリーム50g(ミカエル)', 36000, 1, '', retail, '60%(ミカエル)', retail * 0.15 * 6, 'セット¥36,000÷6÷0.60=定価¥10,000 × 15% × 6 = ¥9,000'],
    ['ビタミンクリーム50g(エンジェル)', 6500, 6, 6500, retail, '65%(エンジェル一律)', retail * 0.20 * 6, '定価¥10,000 × 20% × 6個 = ¥12,000(エンジェルは常に65%)'],
  ]
  const ws4 = XLSX.utils.aoa_to_sheet(s4)
  ws4['!cols'] = [{ wch: 35 }, { wch: 15 }, { wch: 8 }, { wch: 15 }, { wch: 15 }, { wch: 22 }, { wch: 15 }, { wch: 50 }]
  for (const r of [4, 5, 6, 7, 8]) {
    for (const c of ['B', 'D', 'E', 'G']) {
      const ref = `${c}${r}`
      if (ws4[ref] && ws4[ref].v) ws4[ref].z = yenFmt
    }
  }
  XLSX.utils.book_append_sheet(wb, ws4, '計算例')

  // ===== Sheet 5: 代理店設定項目 =====
  const s5 = [
    ['代理店ごとの設定項目'],
    [],
    ['設定項目', '説明', '設定場所'],
    ['KB掛け率(%)', '代理店原価率(45 or 40)。未設定なら従来方式', '代理店管理→詳細'],
    ['自社注文を含める', 'ONなら代理店自身の注文をKB清算に含める(売掛)', '代理店管理→詳細'],
    ['固定調整項目', '業務委託費など毎月の固定加減算', '代理店管理→詳細'],
    ['KBグループ', 'A/B/C グループ分け', '代理店管理→詳細'],
    ['請求書メール', '請求書送付先メールアドレス', '代理店管理→詳細'],
    ['振込先口座', 'KB精算の振込先(銀行名/口座番号等)', '代理店管理→詳細'],
  ]
  const ws5 = XLSX.utils.aoa_to_sheet(s5)
  ws5['!cols'] = [{ wch: 25 }, { wch: 45 }, { wch: 30 }]
  XLSX.utils.book_append_sheet(wb, ws5, '代理店設定項目')

  // ダウンロード
  XLSX.writeFile(wb, 'KB計算ルール.xlsx')
}
